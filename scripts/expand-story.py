for sid,title,subtitle,next_id,line,detail in scenes:
    n=sid.split('-')[0]
    nxt = f"    nextSceneId: '{next_id}',\n" if next_id else ''
    qs=[]
    for i,(text,trust,tension,response) in enumerate(choices[n],1):
        cid=f"scene-{sid}-choice-{i:02d}"
        qs.append(f"      {{ id: '{cid}', text: '{text}', trust: {trust}, tension: {tension}, response: '{response}', memory: 'Ты сделал выбор: {text}.', next: '' }},")
