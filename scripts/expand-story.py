from pathlib import Path

p = Path('app/page.tsx')
s = p.read_text()
marker = "const STORY_EXPANSION_V1 = true;"
if marker in s:
    print('Story expansion already applied.')
    raise SystemExit(0)

anchor = "const DEEP_CONSEQUENCES_V1 = true;"
if anchor not in s:
    raise SystemExit('Deep consequences marker not found')
s = s.replace(anchor, anchor + "\n" + marker, 1)

scene6 = "    id: 'scene-06-morning',"
if scene6 not in s:
    raise SystemExit('Scene 06 not found')
s = s.replace(scene6, scene6 + "\n    nextSceneId: 'scene-07-departure',", 1)

replay_idx = s.find("const replayScenes: Scene[] = [")
if replay_idx < 0:
    raise SystemExit('Replay scenes anchor not found')
chapter_close = s.rfind("  ],", 0, replay_idx)
if chapter_close < 0:
    raise SystemExit('Chapter scenes closing anchor not found')

